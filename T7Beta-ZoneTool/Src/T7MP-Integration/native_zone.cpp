void Test() {
    try {
        requireBuild();
        if (Bots::WeaponMatchActive() || Dvar::GetFloat("cl_ingame") != 0)
            throw std::runtime_error("Return to the frontend before running zone_test");
        const auto source = Mod::Root() / "zone" / "t7zt_probe.ff";
        const auto file = loadFile(source);
        validate(file);
        const auto destination = engineDirectory() / "t7zt_probe.ff";
        if (fs::exists(destination)) {
            if (loadFile(destination) != file)
                throw std::runtime_error("A different t7zt_probe.ff already exists in the engine zone directory");
        } else {
            // No existing zone is overwritten. The engine receives its native
            // registered command through the existing verified command queue.
            fs::copy_file(source, destination, fs::copy_options::none);
        }
        if (!Dvar::Execute("loadzone t7zt_probe"))
            throw std::runtime_error("The native loadzone command could not be queued");
        queued = true;
        Mod::QueueLine("[ZoneTool] Native probe load queued. Run zone_status to check the RawFile asset.");
    } catch (const std::exception& error) {
        Mod::QueueLine(std::string("[ZoneTool] ") + error.what());
    }
}
void Status() {
    try {
        requireBuild();
        Mod::QueueLine("[ZoneTool] Engine fastfile directory: " + engineDirectory().string());
        if (probeResident()) Mod::QueueLine("[ZoneTool] PASS: engine RawFile pool contains the exact native probe text.");
        else Mod::QueueLine(queued ? "[ZoneTool] Probe is not resident yet. Check the engine's loadzone output." :
                                    "[ZoneTool] Probe is not resident. Run zone_test from the frontend.");
        Mod::QueueLine("[ZoneTool] Full Nuketown map serialization is not implemented by this loader test.");
    } catch (const std::exception& error) {
        Mod::QueueLine(std::string("[ZoneTool] ") + error.what());
    }
}
