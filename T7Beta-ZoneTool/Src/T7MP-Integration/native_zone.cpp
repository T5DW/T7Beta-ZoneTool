using Bytes = std::vector<unsigned char>;
constexpr std::uintptr_t directoryAccessor = offsets::aug21::maps::zoneDirectoryAccessor,
                         directoryData = offsets::aug21::maps::zoneDirectoryString;
constexpr unsigned rawfileType = offsets::aug21::maps::rawfileType;
constexpr char zoneName[] = "t7zt_probe";
constexpr char assetName[] = "t7zt/probe.txt";
constexpr char probeText[] = "T7Beta-ZoneTool native fastfile probe - T5DW\n";
constexpr std::uint64_t next = UINT64_MAX;
bool queued{};
template<class T> T read(std::uintptr_t address) {
    T result{};
    if (!utils::hook::read(address, &result, sizeof(result)))
        throw std::runtime_error("Native zone memory is unavailable");
    return result;
}
std::string stringAt(std::uintptr_t address, unsigned limit) {
    std::string result;
    for (unsigned i = 0; address && i < limit; ++i) {
        char value{};
        if (!utils::hook::read(address + i, &value, 1)) return {};
        if (!value) return result;
        if (static_cast<unsigned char>(value) < 32 || static_cast<unsigned char>(value) > 126) return {};
        result += value;
    }
    return {};
}
void requireBuild() {
    if (!BuildProfiles::IsAug21() || !BuildProfiles::Verified())
        throw std::runtime_error("Native zone test supports the verified August 21 build");
    // The accessor returns the engine's configured fastfile directory. Read its
    // data directly only after matching the accessor found in the supplied EXE.
    const unsigned char expected[] = {0x48,0x8d,0x05,0xf9,0x3c,0xe1,0x0b,0xc3};
    if (!patches::verify({patches::image_base() + directoryAccessor, expected, sizeof(expected)}))
        throw std::runtime_error("Fastfile-directory accessor does not match this build");
}
fs::path engineDirectory() {
    auto path = stringAt(patches::image_base() + directoryData, 260);
    if (path.empty()) throw std::runtime_error("Engine fastfile directory is not initialized");
    fs::path directory(path);
    if (!fs::is_directory(directory))
        throw std::runtime_error("Engine fastfile directory does not exist");
    return fs::weakly_canonical(directory);
}
std::uint64_t get(const Bytes& data, std::size_t at, unsigned width) {
    if (at > data.size() || width > data.size() - at) throw std::runtime_error("Truncated probe fastfile");
    std::uint64_t result{};
    for (unsigned i = 0; i < width; ++i) result |= std::uint64_t(data[at+i]) << (i*8);
    return result;
}
void put(Bytes& data, std::size_t at, std::uint64_t value, unsigned width) {
    for (unsigned i = 0; i < width; ++i) data.at(at+i) = static_cast<unsigned char>(value >> (i*8));
}
Bytes expectedBody() {
    Bytes data(96);
    put(data, 0, 1, 8); put(data, 8, next, 8);
    put(data, 32, 1, 8); put(data, 40, next, 8);
    put(data, 56, rawfileType, 8); put(data, 64, next, 8);
    put(data, 72, next, 8); put(data, 80, sizeof(probeText)-1, 8); put(data, 88, next, 8);
    data.insert(data.end(), assetName, assetName + sizeof(assetName));
    data.insert(data.end(), probeText, probeText + sizeof(probeText));
    return data;
}
Bytes loadFile(const fs::path& path) {
    const auto length = fs::file_size(path);
    if (length < 600 || length > 65536) throw std::runtime_error("Invalid loader probe size");
    std::ifstream input(path, std::ios::binary);
    Bytes bytes((std::istreambuf_iterator<char>(input)), {});
    if (!input || bytes.size() != length) throw std::runtime_error("Cannot read complete loader probe");
    return bytes;
}
void validate(const Bytes& file) {
    const auto body = expectedBody();
    constexpr std::size_t h = 0x248, start = h + 16;
    const auto aligned = (body.size() + 3) & ~std::size_t(3);
    if (file.size() != start + aligned + 80 || std::memcmp(file.data(), "TAff0000", 8) ||
        get(file, 8, 4) != 0x1fb || get(file, 12, 4) != 0 ||
        std::memcmp(file.data() + 248, zoneName, sizeof(zoneName)) || get(file, 144, 8) != body.size() ||
        get(file, h, 4) != body.size() || get(file, h+4, 4) != body.size() ||
        get(file, h+8, 4) != aligned || get(file, h+12, 4) != h ||
        !std::equal(body.begin(), body.end(), file.begin()+start) ||
        get(file, start+aligned, 8) != 0 || get(file, start+aligned+8, 4) != 0 ||
        get(file, start+aligned+12, 4) != start+aligned)
        throw std::runtime_error("Expected the stored t7zt_probe.ff generated by native_zone.py");
    if (get(file, 168, 8) < 96 || get(file, 168+5*8, 8) < body.size())
        throw std::runtime_error("Loader probe allocation capacities are too small");
}
bool probeResident() {
    using namespace offsets::aug21::maps;
    auto descriptor = patches::image_base() + pools + rawfileType * poolStride;
    auto data = read<std::uintptr_t>(descriptor);
    auto stride = read<unsigned>(descriptor+8), capacity = read<unsigned>(descriptor+12), used = read<unsigned>(descriptor+20);
    if (stride != 24 || !capacity || capacity > 65536 || used > capacity || !data)
        throw std::runtime_error("RawFile pool does not match the beta layout");
    for (unsigned i=0; i<capacity; ++i) {
        auto record = data + i*stride;
        if (stringAt(read<std::uintptr_t>(record), 128) != assetName) continue;
        if (read<std::uint32_t>(record+8) != sizeof(probeText)-1) return false;
        std::array<char, sizeof(probeText)> text{};
        return utils::hook::read(read<std::uintptr_t>(record+16), text.data(), text.size()) &&
            std::memcmp(text.data(), probeText, text.size()) == 0;
    }
    return false;
}
